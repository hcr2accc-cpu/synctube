    fun songs(n: Int): String {
        val word = when {
            n % 10 == 1 && n % 100 != 11 -> "pesma"
            n % 10 in 2..4 && n % 100 !in 12..14 -> "pesme"
            else -> "pesama"
        }
        return "$n $word"
    }

